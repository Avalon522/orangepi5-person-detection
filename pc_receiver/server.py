import os
import base64
import binascii
import json
import threading
import uuid
import time
from datetime import datetime
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse

HOST = os.environ.get("MONITOR_HOST", "127.0.0.1")
PORT = 8000
ROOT = Path(__file__).resolve().parent
LOG = ROOT / "alerts.jsonl"
IMAGES = ROOT / "images"
IMAGES.mkdir(exist_ok=True)
LOCK = threading.Lock()

HTML = (ROOT / 'dashboard.html').read_text(encoding='utf-8')
STATUS = {}
LIVE = {"jpeg": None, "seq": 0}



class Handler(BaseHTTPRequestHandler):
    def send_bytes(self, status, body, content_type):
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def reply(self, status, data):
        self.send_bytes(
            status,
            json.dumps(data, ensure_ascii=False).encode("utf-8"),
            "application/json; charset=utf-8",
        )

    def do_GET(self):
        path = urlparse(self.path).path
        if path == "/":
            self.send_bytes(200, HTML.encode("utf-8"), "text/html; charset=utf-8")
            return

        if path == "/live.mjpg":
            self.send_response(200)
            self.send_header("Content-Type", "multipart/x-mixed-replace; boundary=frame")
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            previous = -1
            try:
                while True:
                    with LOCK:
                        jpeg, seq = LIVE["jpeg"], LIVE["seq"]
                    if jpeg is not None and seq != previous:
                        self.wfile.write(b"--frame\r\nContent-Type: image/jpeg\r\nContent-Length: " + str(len(jpeg)).encode() + b"\r\n\r\n" + jpeg + b"\r\n")
                        self.wfile.flush()
                        previous = seq
                    time.sleep(0.02)
            except OSError:
                pass
            return
        if path == "/api/status":
            with LOCK:
                state = dict(STATUS)
            state["online"] = time.monotonic() - state.pop("seen", -100000) < 6
            self.reply(200, state)
            return

        if path == "/api/events":
            events = []
            with LOCK:
                if LOG.exists():
                    from collections import deque
                    with LOG.open(encoding="utf-8") as file:
                        for line in deque(file, maxlen=100):
                            try:
                                item = json.loads(line)
                                if isinstance(item, dict):
                                    events.append(item)
                            except ValueError:
                                continue
            self.reply(200, list(reversed(events)))
            return

        if path.startswith("/images/"):
            name = path.removeprefix("/images/")
            # Only serve filenames generated by this application.
            stem = name.removesuffix(".jpg")
            if (
                name.endswith(".jpg")
                and len(stem) == 32
                and all(c in "0123456789abcdef" for c in stem)
            ):
                image = IMAGES / name
                if image.is_file():
                    self.send_bytes(200, image.read_bytes(), "image/jpeg")
                    return

        self.reply(404, {"error": "Not found"})

    def do_POST(self):
        if self.path == "/api/frame":
            try:
                length = int(self.headers.get("Content-Length", "0"))
                count = int(self.headers.get("X-Person-Count", "-1"))
                if not 0 < length <= 4194304 or count < 0:
                    raise ValueError("Invalid frame")
                jpeg = self.rfile.read(length)
                if len(jpeg) != length or not jpeg.startswith(b"\xff\xd8\xff"):
                    raise ValueError("Invalid JPEG")
                with LOCK:
                    LIVE.update(jpeg=jpeg, seq=LIVE["seq"]+1)
                    STATUS.update(person_count=count, seen=time.monotonic(), received_at=datetime.now().astimezone().isoformat(timespec="seconds"))
                self.reply(200, {"status":"ok"})
            except ValueError as exc:
                self.reply(400, {"error":str(exc)})
            return
        if self.path == "/api/status":
            try:
                length = int(self.headers.get("Content-Length", "0"))
                if not 0 < length <= 4096:
                    raise ValueError("Invalid size")
                state = json.loads(self.rfile.read(length))
                count = state.get("person_count")
                if type(count) is not int or count < 0:
                    raise ValueError("Invalid count")
                with LOCK:
                    STATUS.update(person_count=count, seen=time.monotonic(),
                                  received_at=datetime.now().astimezone().isoformat(timespec="seconds"))
                self.reply(200, {"status": "ok"})
            except (ValueError, AttributeError) as exc:
                self.reply(400, {"error": str(exc)})
            return
        if self.path != "/api/alert":
            self.reply(404, {"error": "Unknown endpoint"})
            return

        try:
            length = int(self.headers.get("Content-Length", "0"))
            if not 0 < length <= 4 * 1024 * 1024:
                raise ValueError("Message must be between 1 byte and 4 MiB")

            event = json.loads(self.rfile.read(length).decode("utf-8"))
            if not isinstance(event, dict):
                raise ValueError("JSON must be an object")

            count = event.get("person_count")
            score = event.get("max_confidence")
            if type(count) is not int or count < 0:
                raise ValueError("Invalid person_count")
            if type(score) not in (int, float) or not 0 <= score <= 1:
                raise ValueError("Invalid max_confidence")

            image_data = None
            encoded = event.get("image_base64")
            if encoded is not None:
                if not isinstance(encoded, str):
                    raise ValueError("Invalid image_base64")
                image_data = base64.b64decode(encoded, validate=True)
                if not image_data.startswith(b"\xff\xd8\xff"):
                    raise ValueError("Expected JPEG image")

        except (ValueError, UnicodeError, binascii.Error) as exc:
            self.reply(400, {"error": str(exc)})
            return

        event_id = uuid.uuid4().hex
        record = {
            "id": event_id,
            "device_id": str(event.get("device_id", "unknown"))[:100],
            "event_time": str(event.get("event_time", ""))[:100],
            "received_at": datetime.now().astimezone().isoformat(
                timespec="seconds"
            ),
            "source_ip": self.client_address[0],
            "person_count": count,
            "max_confidence": score,
            "test": event.get("test") is True,
        }

        try:
            with LOCK:
                if image_data is not None:
                    (IMAGES / f"{event_id}.jpg").write_bytes(image_data)
                    record["image_url"] = f"/images/{event_id}.jpg"
                with LOG.open("a", encoding="utf-8") as file:
                    file.write(json.dumps(record, ensure_ascii=False) + "\n")
        except OSError as exc:
            print("Save failed:", exc, flush=True)
            self.reply(500, {"error": "Cannot save event"})
            return

        print(
            f"[ALERT] {record['received_at']} persons={count} "
            f"confidence={score:.3f} image={image_data is not None}",
            flush=True,
        )
        self.reply(200, {"status": "ok", "id": event_id})

    def log_message(self, format, *args):
        # Avoid printing every browser polling request.
        pass


if __name__ == "__main__":
    server = ThreadingHTTPServer((HOST, PORT), Handler)
    print(f"Dashboard: http://{HOST}:{PORT}", flush=True)
    print(f"Log file: {LOG}", flush=True)
    print("Press Ctrl+C to stop.", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nStopped.")
    finally:
        server.server_close()